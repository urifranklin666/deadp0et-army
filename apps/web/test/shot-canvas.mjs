import { chromium } from "playwright";
const SP = process.env.SP, APP = "https://deadp0et.army/app/";
const rnd = () => Math.random().toString(36).slice(2,7);
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1280, height: 800 } });
const pg = await ctx.newPage();
const cdp = await ctx.newCDPSession(pg);
await cdp.send("WebAuthn.enable");
await cdp.send("WebAuthn.addVirtualAuthenticator",{options:{protocol:"ctap2",transport:"internal",hasResidentKey:true,hasUserVerification:true,isUserVerified:true,automaticPresenceSimulation:true}});
await pg.goto(APP,{waitUntil:"networkidle"});
await pg.getByPlaceholder("ghost_01").fill("art_"+rnd());
await pg.getByRole("button",{name:"Create passkey"}).click();
await pg.getByRole("button",{name:"New channel"}).waitFor({timeout:90000});
const slug="studio-"+rnd();
await pg.getByRole("button",{name:"New channel"}).click();
await pg.getByPlaceholder("war-room").fill(slug);
await pg.getByRole("button",{name:"Create",exact:true}).click();
await pg.getByText(slug,{exact:true}).first().waitFor({timeout:60000});
await pg.getByRole("button",{name:"Canvas"}).click();
await pg.locator("canvas").waitFor({timeout:30000});
const box = await pg.locator("canvas").boundingBox();
const stroke = async (pts) => {
  await pg.mouse.move(box.x+pts[0][0], box.y+pts[0][1]); await pg.mouse.down();
  for (const [x,y] of pts.slice(1)) await pg.mouse.move(box.x+x, box.y+y,{steps:8});
  await pg.mouse.up(); await pg.waitForTimeout(500);
};
await stroke([[120,120],[260,200],[400,120],[540,220],[680,120]]);
await pg.getByLabel("Colour #0ea5c4").click();
await pg.getByLabel("Width 8").click();
await stroke([[150,320],[300,380],[450,300],[620,400]]);
await pg.getByLabel("Colour #e879f9").click();
await pg.getByLabel("Width 16").click();
await stroke([[200,480],[340,440],[480,500]]);
await pg.waitForTimeout(2000);
await pg.screenshot({ path: `${SP}/canvas-final.png` });
console.log("captured");
await b.close();
